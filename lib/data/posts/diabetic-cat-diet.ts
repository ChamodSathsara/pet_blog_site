  content: `A hidden leak rarely begins with water pouring through the ceiling. More often it starts as a higher bill, a faint stain, a cabinet that smells musty, or a meter that moves when every fixture is off.

## Run the water-meter test

Turn off faucets, irrigation, ice makers, dishwashers, washing machines, and any appliance that intentionally uses water. Do not use water during the test. Record the meter reading, wait 30 to 60 minutes, and read it again. Movement suggests water is passing through the system.

First check toilets. Add a few drops of food coloring to each tank and wait without flushing. Color in the bowl means the flapper or flush valve is leaking. Then check irrigation valves, hose bibs, water softeners, and the temperature-and-pressure relief discharge at the water heater.

## Read the clues

- A warm spot on a slab may indicate a hot-water line leak.
- Peeling paint, swollen trim, or a soft baseboard suggests repeated wetting.
- A stain that grows after rain points toward the roof or exterior, not supply plumbing.
- A musty odor with no visible water may indicate a slow drain, shower-pan, or condensation problem.
- A running sound when fixtures are off deserves prompt investigation.

Use a pinless moisture meter to compare the suspicious area with a known-dry area made from the same material. It can confirm a pattern, but it cannot identify the source by itself.

## Know when to stop

Close the main shutoff and call a plumber for active water, a rapidly changing meter, wet electrical equipment, a bulging ceiling, sewage, or suspected leaks under a slab. Do not cut into a wall until electrical, gas, and plumbing routes have been considered.

Document the meter readings, photos, and times when moisture appears. Those details help a plumber locate the source faster and may support an insurance claim.`
